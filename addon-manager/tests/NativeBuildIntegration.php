#!/usr/bin/env php
<?php
declare(strict_types=1);

$standaloneAssetSuite = !isset($suite);
if ($standaloneAssetSuite) {
    require dirname(__DIR__) . '/bootstrap.php';
    require __DIR__ . '/Support.php';
}

use AddonManager\Runner\IsolatedRunner;
use AddonManager\Storage\Files;
use AddonManager\Tests\Suite;
use function AddonManager\Tests\{check, rejects, same, temporary, write};

/** Independently encode the bounded stream emitted by the isolated Node build. */
function assetPacket(string $path, array $entries, string $suffix = ''): string
{
    $bytes = "AMASSET01\n";
    foreach ($entries as $entry) {
        $name = $entry['name'];
        $content = $entry['bytes'] ?? '';
        $bytes .= pack('nN', strlen($name), $entry['size'] ?? strlen($content)) . $name . $content;
    }
    write($path, $bytes . pack('nN', 0, 0) . $suffix);
    return $path;
}

function assetReceiver(string $root, string $packet): void
{
    $runner = new IsolatedRunner($root . '/panel', $root . '/state');
    // Exercise the real parser without requiring another expensive Panel build.
    (new ReflectionMethod(IsolatedRunner::class, 'receiveAssets'))->invoke($runner, $packet, $root . '/stage');
}

function assetFixture(string $root): array
{
    write($root . '/stage/public/assets/old.js', 'original asset');
    write($root . '/stage/resources/scripts/untouched.ts', 'original source');
    write($root . '/escaped.txt', 'outside sentinel');
    return Files::inventory($root . '/stage');
}

function rejectedAssetPacket(string $root, string $packet, array $before, ?string $reason = null): void
{
    rejects(static fn () => assetReceiver($root, $packet), $reason);
    same($before, Files::inventory($root . '/stage'), 'Rejected generated output changed staged code or assets');
    same('outside sentinel', file_get_contents($root . '/escaped.txt'), 'Generated output escaped its private receiving directory');
}

if ($standaloneAssetSuite) $suite = new Suite();
$mainBytes = 'export const fixture = true;';
$cssBytes = 'body { color: teal; }';
$metadata = ['name' => 'manifest.json', 'bytes' => json_encode([
    'main.js' => ['src' => '/assets/app.js', 'integrity' => 'sha384-' . base64_encode(hash('sha384', $mainBytes, true))],
    'app.css' => ['src' => '/assets/nested/app.css', 'integrity' => 'sha384-' . base64_encode(hash('sha384', $cssBytes, true))],
], JSON_THROW_ON_ERROR)];

$suite->test('native-assets', 'verified generated output replaces shared assets while preserving composed source', function () use ($metadata): void {
    temporary(function (string $root) use ($metadata): void {
        assetFixture($root);
        $packet = assetPacket($root . '/job/output.assets', [$metadata, ['name' => 'app.js', 'bytes' => 'export const fixture = true;'], ['name' => 'nested/app.css', 'bytes' => 'body { color: teal; }']]);
        assetReceiver($root, $packet);
        check(!is_file($root . '/stage/public/assets/old.js'), 'Receiver retained stale shared bundles');
        same('export const fixture = true;', file_get_contents($root . '/stage/public/assets/app.js'));
        same('body { color: teal; }', file_get_contents($root . '/stage/public/assets/nested/app.css'));
        same($metadata['bytes'], file_get_contents($root . '/stage/public/assets/manifest.json'));
        same('original source', file_get_contents($root . '/stage/resources/scripts/untouched.ts'));
    });
});

foreach (['../escaped.txt', '/tmp/escaped.txt', 'C:/escaped.js', 'nested\\escaped.js', 'nested/../../escaped.txt', '.env', 'shell.php'] as $name) {
    $suite->test('native-assets', 'unsafe generated path rejects before changing existing assets: ' . $name, function () use ($name, $metadata): void {
        temporary(function (string $root) use ($name, $metadata): void {
            $before = assetFixture($root);
            if ($name === '/tmp/escaped.txt') $name = $root . '/escaped.txt';
            $packet = assetPacket($root . '/job/output.assets', [$metadata, ['name' => $name, 'bytes' => 'unsafe generated bytes']]);
            rejectedAssetPacket($root, $packet, $before, '/path|relative|target|protected|forbidden|unsafe/i');
        });
    });
}

foreach ([
    'duplicate file' => [['name' => 'app.js', 'bytes' => 'one'], ['name' => 'app.js', 'bytes' => 'two']],
    'case-colliding file' => [['name' => 'App.js', 'bytes' => 'one'], ['name' => 'app.js', 'bytes' => 'two']],
    'case-colliding implicit directory' => [['name' => 'Chunks/one.js', 'bytes' => 'one'], ['name' => 'chunks/two.js', 'bytes' => 'two']],
] as $name => $entries) {
    $suite->test('native-assets', $name . ' rejects the complete generated output', function () use ($entries, $metadata): void {
        temporary(function (string $root) use ($entries, $metadata): void {
            $before = assetFixture($root);
            rejectedAssetPacket($root, assetPacket($root . '/job/output.assets', [$metadata, ...$entries]), $before, '/overlap|duplicate|collid|case/i');
        });
    });
}

$suite->test('native-assets', 'oversized declared asset rejects without reading or deploying its payload', function () use ($metadata): void {
    temporary(function (string $root) use ($metadata): void {
        $before = assetFixture($root);
        $packet = assetPacket($root . '/job/output.assets', [$metadata, ['name' => 'huge.js', 'size' => 64 * 1024 * 1024 + 1, 'bytes' => '']]);
        rejectedAssetPacket($root, $packet, $before, '/limit|bounded|exceed/i');
    });
});

$suite->test('native-assets', 'oversized manifest rejects before allocating or parsing its declared JSON payload', function (): void {
    temporary(function (string $root): void {
        $before = assetFixture($root);
        $packet = assetPacket($root . '/job/output.assets', [['name' => 'manifest.json', 'size' => 2 * 1024 * 1024 + 1, 'bytes' => '']]);
        rejectedAssetPacket($root, $packet, $before, '/manifest.*bounded.*limit/i');
    });
});

$suite->test('native-assets', 'aggregate asset expansion budget rejects individually bounded records', function () use ($metadata): void {
    temporary(function (string $root) use ($metadata): void {
        $before = assetFixture($root);
        $path = $root . '/job/output.assets';
        write($path, "AMASSET01\n");
        $stream = fopen($path, 'r+b');
        fseek($stream, 0, SEEK_END);
        fwrite($stream, pack('nN', strlen($metadata['name']), strlen($metadata['bytes'])) . $metadata['name'] . $metadata['bytes']);
        foreach (['first.js', 'second.js'] as $name) {
            fwrite($stream, pack('nN', strlen($name), 64 * 1024 * 1024) . $name);
            // Sparse content avoids allocating a huge fixture string in PHP memory.
            fseek($stream, 64 * 1024 * 1024, SEEK_CUR);
        }
        fwrite($stream, pack('nN', 0, 0));
        fclose($stream);
        rejectedAssetPacket($root, $path, $before, '/limit|bounded|exceed/i');
    });
});

$suite->test('native-assets', 'generated entry budget rejects an excessive stream', function () use ($metadata): void {
    temporary(function (string $root) use ($metadata): void {
        $before = assetFixture($root);
        $entries = [$metadata];
        for ($index = 0; $index < 4096; $index++) $entries[] = ['name' => 'chunks/' . sprintf('%04d', $index) . '.js', 'bytes' => ''];
        rejectedAssetPacket($root, assetPacket($root . '/job/output.assets', $entries), $before, '/limit|bounded|exceed/i');
    });
});

$suite->test('native-assets', 'missing or malformed manifest cannot replace working shared bundles', function (): void {
    temporary(function (string $root): void {
        $before = assetFixture($root);
        rejectedAssetPacket($root, assetPacket($root . '/missing/output.assets', [['name' => 'app.js', 'bytes' => 'bundle']]), $before, '/manifest|termination/i');
        rejectedAssetPacket($root, assetPacket($root . '/malformed/output.assets', [['name' => 'manifest.json', 'bytes' => '{']]), $before, '/manifest|json|syntax/i');
    });
});

$suite->test('native-assets', 'manifest references must resolve to received nonempty files', function () use ($metadata): void {
    temporary(function (string $root) use ($metadata): void {
        $before = assetFixture($root);
        rejectedAssetPacket($root, assetPacket($root . '/missing-file/output.assets', [$metadata]), $before, '/missing|invalid asset/i');
        rejectedAssetPacket($root, assetPacket($root . '/empty-file/output.assets', [$metadata, ['name' => 'app.js', 'bytes' => '']]), $before, '/missing|invalid asset/i');
    });
});

$suite->test('native-assets', 'SHA384 integrity mismatch rejects complete output before replacing bundles', function () use ($metadata, $cssBytes): void {
    temporary(function (string $root) use ($metadata, $cssBytes): void {
        $before = assetFixture($root);
        $packet = assetPacket($root . '/job/output.assets', [$metadata, ['name' => 'app.js', 'bytes' => 'tampered JavaScript'], ['name' => 'nested/app.css', 'bytes' => $cssBytes]]);
        rejectedAssetPacket($root, $packet, $before, '/integrity.*match/i');
    });
});

$suite->test('native-assets', 'manifest object and integrity mapping types are strict', function () use ($metadata, $mainBytes, $cssBytes): void {
    temporary(function (string $root) use ($metadata, $mainBytes, $cssBytes): void {
        $before = assetFixture($root);
        $manifest = json_decode($metadata['bytes'], true, 512, JSON_THROW_ON_ERROR);
        $invalid = $manifest;
        $invalid['main.js']['integrity'] = 123;
        $extra = $manifest;
        $extra['main.js']['command'] = 'arbitrary installer';
        foreach (['[]', json_encode($invalid, JSON_THROW_ON_ERROR), json_encode($extra, JSON_THROW_ON_ERROR)] as $index => $bytes) {
            $packet = assetPacket($root . '/job-' . $index . '/output.assets', [['name' => 'manifest.json', 'bytes' => $bytes], ['name' => 'app.js', 'bytes' => $mainBytes], ['name' => 'nested/app.css', 'bytes' => $cssBytes]]);
            rejectedAssetPacket($root, $packet, $before, '/main.js|integrity|manifest/i');
        }
    });
});

$suite->test('native-assets', 'manifest asset URLs cannot leave the generated public asset directory', function () use ($metadata, $mainBytes, $cssBytes): void {
    temporary(function (string $root) use ($metadata, $mainBytes, $cssBytes): void {
        $before = assetFixture($root);
        foreach (['https://example.invalid/app.js', '/assets/../outside.js'] as $index => $url) {
            $manifest = json_decode($metadata['bytes'], true, 512, JSON_THROW_ON_ERROR);
            $manifest['main.js']['src'] = $url;
            $packet = assetPacket($root . '/job-' . $index . '/output.assets', [['name' => 'manifest.json', 'bytes' => json_encode($manifest, JSON_THROW_ON_ERROR)], ['name' => 'app.js', 'bytes' => $mainBytes], ['name' => 'nested/app.css', 'bytes' => $cssBytes]]);
            rejectedAssetPacket($root, $packet, $before, '/mapping|relative|path|target|unsafe/i');
        }
    });
});

$suite->test('native-assets', 'truncated records wrong protocol and trailing bytes reject the entire stream', function () use ($metadata): void {
    temporary(function (string $root) use ($metadata): void {
        $before = assetFixture($root);
        $packet = assetPacket($root . '/truncated/output.assets', [$metadata, ['name' => 'app.js', 'bytes' => 'abc', 'size' => 1024]]);
        rejectedAssetPacket($root, $packet, $before, '/truncated/i');
        $packet = assetPacket($root . '/protocol/output.assets', [$metadata]);
        write($packet, 'WRONGMAGIC' . substr(file_get_contents($packet), 10));
        rejectedAssetPacket($root, $packet, $before, '/protocol/i');
        rejectedAssetPacket($root, assetPacket($root . '/trailing/output.assets', [$metadata], 'hidden trailing data'), $before, '/termination|invalid/i');
    });
});

if ($standaloneAssetSuite) {
    try { exit($suite->run(array_slice($argv, 1))); }
    catch (Throwable $error) { fwrite(STDERR, $error->getMessage() . PHP_EOL); exit(2); }
}
